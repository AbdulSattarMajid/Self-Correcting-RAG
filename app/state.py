from typing import List, TypedDict


class GraphState(TypedDict):
    """
    Represents the memory state of our graph.

    Attributes:
        question: The original user question.
        documents: Context passed to the generator (parent chunks from the
            local DB, plus Tavily web results if the fallback ran).
        web_search: 'Yes' or 'No' flag; whether the Tavily fallback is needed.
        generation: The final answer generated by Gemini.
        grounded: 'yes' or 'no'; the hallucination critic's verdict on the generation.
        retries: How many times the critic has checked a generation so far.
    """
    question: str
    documents: List[str]
    web_search: str
    generation: str
    grounded: str
    retries: int